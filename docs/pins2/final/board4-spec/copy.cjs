// Board 4 — EVERY VISIBLE STRING IN THE KIT'S DESIGN CODE: the copy a person reads (labels, hints, empty and error lines, pop-up titles,
// confirm questions, rule messages), listed per file with its line, so a port can carry the words and not only the looks. Written
// 2026-10-01 10:33 EDT by the readiness audit (findings D-07, D-10, D-11, D-12, D-16, K1-09): structure.md cuts leaf text at 28 characters
// and the value files at about 48, and copy that only appears in a state the walker never opens reached no file at all.
// Static: it reads the kit's source, needs no server, and runs anywhere in the regenerate command. A string here is a CANDIDATE for copy —
// the filters drop class lists, selectors, paths and code, and a short label can still slip through; the known-case asserts below prove
// the extraction reaches the strings the audit found missing. Writes `copy.md`. Run: node docs/pins2/final/board4-spec/copy.cjs
const KITC = require('./kit.cjs'); // which board: Collective's kit, or Final after a bake (kit.cjs)
const fs = require('fs'); const path = require('path');
const KIT = KITC.DIR;
// The design code (file-map.md: DESIGN-CODE and the design half of MIXED); gates4/ and the gate frames are chrome.
const DIRS = ['b3', 'b4', 'ui', 'gates'];
const SKIP = /\.test\.m?js$|^(main|picks|shared)\.js$/;
const files = DIRS.flatMap((d) => fs.readdirSync(path.join(KIT, d)).filter((f) => /\.m?js$/.test(f) && !SKIP.test(f)).map((f) => `${d}/${f}`)).sort();

const ATTR = /\b(title|sub|placeholder|aria-label|label|hint|alt|text|empty|note|ask|lead|tip)=(?:"([^"$]{2,})"|'([^'$]{2,})'|\$\{\s*['"]([^'"]{2,})['"]\s*\})/g;
const TEXT = />([^<>`{}]*[A-Za-z][^<>`{}]*)</g;
const LIT = /(['"‘’])((?:(?!\1)[^\\\n]){3,}?)\1/g;
const looksLikeCopy = (s) => {
  const t = s.trim();
  if (t.length < 3 || !/[A-Za-z]/.test(t)) return false;
  if (s !== s.trimStart() && s !== s.trimEnd()) return false; // the gap BETWEEN two literals (' + cls + '), not a literal
  if (/^[.#]|\s[+?:]\s|^[+?:)\]]|[(+?:[]$/.test(t)) return false; // a selector list or a concatenation fragment
  if (/^[\w.:#\-[\]=*>+~ ()]+$/.test(t) && !/\s[a-z]+\s/.test(t) && !/^[A-Z][a-z]/.test(t)) return false; // a selector or class list
  if (/^(--|var\(|#[0-9a-f]{3,8}$|\.\/|\.\.\/|https?:|data:|M\d|[a-z-]+:)/i.test(t)) return false; // tokens, paths, svg paths, css props
  if (/[{};=]|=>|\|\||&&|\$\{/.test(t)) return false; // code
  if (/^[a-z][a-zA-Z0-9]*$/.test(t)) return false; // an identifier
  if (/^[a-z0-9-]+( [a-z0-9-]+)*$/.test(t) && !/\b(the|a|an|to|of|and|or|in|on|no|is|it|this|that|its|with|for|by|from|one|every|each|yet|not|can)\b/.test(t)) return false; // class names
  return true;
};

const rows = []; const seen = new Set();
for (const f of files) {
  const src = fs.readFileSync(path.join(KIT, f), 'utf8');
  const lines = src.split('\n');
  lines.forEach((ln, i) => {
    if (/^\s*(\/\/|\*|\/\*)/.test(ln)) return; // comments are notes, not copy
    const found = [];
    for (const m of ln.matchAll(ATTR)) found.push([m[1], m[2] || m[3] || m[4]]);
    for (const m of ln.matchAll(TEXT)) found.push(['text', m[1]]);
    for (const m of ln.matchAll(LIT)) found.push(['string', m[2], true]);
    for (const [kind, raw, lit] of found) {
      const s = raw.replace(/\s+/g, ' ').trim();
      if (!looksLikeCopy(lit ? raw : s)) continue;
      const key = `${f}|${s}`;
      if (seen.has(key)) continue;
      seen.add(key);
      rows.push({ f, line: i + 1, kind, s });
    }
  });
}

// Known cases — the strings the audit found in no document. If one is missing, the extraction is broken, not the kit.
const KNOWN = ['Nothing is deleted yet', 'Discard on Review and every build comes back.', 'A tier can’t sit with ASS',
  'Only the first line and one attachment are needed.', 'Copy failed — select the text', 'No event matches these filters.'];
const missing = KNOWN.filter((k) => !rows.some((r) => r.s.includes(k)));
if (missing.length) { console.error(`copy.cjs: known strings not extracted: ${missing.join(' · ')}`); process.exit(1); }

const esc = (s) => s.replace(/\|/g, '\\|');
const byFile = files.map((f) => [f, rows.filter((r) => r.f === f)]).filter(([, r]) => r.length);
const out = ['---', 'kind: reference', 'status: live', '---', '',
  '# ' + KITC.TITLE + ' — every visible string in the kit, generated', '',
  `*Generated by \`copy.cjs\` from the kit's design code (${files.length} files under \`${KITC.REL}/\`: ${DIRS.map((d) => `\`${d}/\``).join(', ')}; the gate frames and \`gates4/\` are chrome). ${rows.length} strings. A row is a candidate — the words a person reads, found in a template's text, a copy attribute or a string literal; open the line for the state that shows it. Static: no server needed, so it never misses a state the walker never opens.*`, ''];
for (const [f, rs] of byFile) {
  out.push(`## \`${f}\` — ${rs.length}`, '', '| Line | Kind | Text |', '|---|---|---|');
  for (const r of rs) out.push(`| ${r.line} | ${r.kind} | ${esc(r.s)} |`);
  out.push('');
}
fs.writeFileSync(path.join(__dirname, 'copy.md'), out.join('\n'));
console.log(`copy.md: ${rows.length} strings from ${byFile.length} of ${files.length} files · known cases ${KNOWN.length}/${KNOWN.length}`);
